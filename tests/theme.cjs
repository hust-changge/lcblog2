const assert = require('node:assert/strict');
const { readFileSync } = require('node:fs');
const { resolve } = require('node:path');
const { runInNewContext } = require('node:vm');
const source = readFileSync(resolve(__dirname, '../B1gchangBlog-Frontend/src/utils/theme.js'), 'utf8').replaceAll('export ', '');
const dataset = {};
let saved;
const storage = { getItem: () => saved, setItem: (key, value) => { saved = value; } };
const context = { document: { documentElement: { dataset } }, localStorage: storage };
const api = runInNewContext(source + '\n({setTheme, initTheme})', context);
assert.equal(api.initTheme(), 'dark');
assert.equal(api.setTheme('light'), 'light');
assert.equal(dataset.theme, 'light');
assert.equal(saved, 'light');
assert.equal(api.initTheme(), 'light');
saved = 'invalid';
assert.equal(api.initTheme(), 'dark');
storage.getItem = storage.setItem = () => { throw new Error('Storage blocked'); };
assert.equal(api.initTheme(), 'dark');
assert.equal(api.setTheme('light'), 'light');
assert.equal(dataset.theme, 'light');
console.log('PASS: default, switching, persisted preference, invalid value and blocked storage.');
